import { NextResponse } from "next/server";
import { z } from "zod";
import tzlookup from "@photostructure/tz-lookup";
import { calculateKundliAtInstant } from "@/lib/astrology";
import { checkRateLimit } from "@/lib/rate-limit";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

const schema = z.object({
  place: z.string().trim().min(2).max(300),
  latitude: z.number().min(-90).max(90),
  longitude: z.number().min(-180).max(180),
});

export async function POST(request: Request) {
  const rate = await checkRateLimit(request, "transits", 10, 60_000);
  if (!rate.available) return NextResponse.json({ error: "The shared rate-limiting service is unavailable. Configure migration 004 and the server-only service-role key, then retry." }, { status: 503 });
  if (!rate.allowed) return NextResponse.json({ error: "Too many transit calculations. Please wait and try again." }, { status: 429, headers: { "Retry-After": String(rate.retryAfterSeconds) } });

  try {
    const input = schema.parse(await request.json());
    const timezone = tzlookup(input.latitude, input.longitude);
    const instant = new Date();
    const parts = Object.fromEntries(new Intl.DateTimeFormat("en-GB", {
      timeZone: timezone, year: "numeric", month: "2-digit", day: "2-digit",
      hour: "2-digit", minute: "2-digit", hourCycle: "h23",
    }).formatToParts(instant).map((part) => [part.type, part.value]));
    const report = calculateKundliAtInstant({
      ...input,
      timezone,
      date: parts.year + "-" + parts.month + "-" + parts.day,
      time: parts.hour + ":" + parts.minute,
    }, instant);
    return NextResponse.json({
      calculatedAt: instant.toISOString(),
      timezone,
      experimental: true,
      note: "Current transit positions are generated by Vedic AI's experimental Astronomy Engine/Lahiri-approximation calculation. Validate against an independent ephemeris before relying on them.",
      report,
    }, { headers: { "Cache-Control": "private, no-store", "X-Content-Type-Options": "nosniff" } });
  } catch (error) {
    if (error instanceof z.ZodError) return NextResponse.json({ error: "Provide a valid place label and coordinates." }, { status: 400 });
    return NextResponse.json({ error: "Current transits could not be calculated. Verify the location and try again." }, { status: 422 });
  }
}
